const t = (s) => (I18N.lang === 'kk' && s != null && Object.prototype.hasOwnProperty.call(KK, s) ? KK[s] : s);
const L = (ru, kk) => (I18N.lang === 'kk' ? kk : ru);
// первая буква строчная: «Регистратор» → «8 арналы регистратор»
const lc = (s) => s.charAt(0).toLowerCase() + s.slice(1);
// посчитать по-русски (заявка в CRM), не меняя язык страницы
function inRu(fn) {
  const was = I18N.lang;
  I18N.lang = 'ru';
  try { return fn(); } finally { I18N.lang = was; }
}

// ---------- вёрстка: тексты и подписи страницы переводятся по словарю, оригинал помним ----------
const I18N_ATTRS = ['aria-label', 'placeholder'];
const origText = new WeakMap(), origAttr = new WeakMap();
const origHead = { title: document.title, desc: document.querySelector('meta[name="description"]')?.content };

function translatePage() {
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement.closest('script, style, [data-i18n-skip]') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n; (n = walk.nextNode());) {
    if (!origText.has(n)) {
      const s = n.nodeValue.trim();
      if (!s || !Object.prototype.hasOwnProperty.call(KK, s)) continue;
      origText.set(n, n.nodeValue);
    }
    const o = origText.get(n);
    n.nodeValue = o.replace(o.trim(), t(o.trim()));
  }
  for (const el of document.body.querySelectorAll(I18N_ATTRS.map((a) => `[${a}]`).join(','))) {
    if (el.closest('[data-i18n-skip]')) continue;
    let o = origAttr.get(el);
    if (!o) origAttr.set(el, (o = Object.fromEntries(I18N_ATTRS.filter((a) => el.hasAttribute(a)).map((a) => [a, el.getAttribute(a)]))));
    for (const [a, v] of Object.entries(o)) el.setAttribute(a, t(v));
  }
  document.title = t(origHead.title);
  const d = document.querySelector('meta[name="description"]');
  if (d && origHead.desc) d.content = t(origHead.desc);
  document.documentElement.lang = LANGS.find((l) => l.id === I18N.lang).html;
}

// ---------- переключатель в шапке: капсула с круглым флагом и названием, по нажатию — меню ----------
const CHEV = '<svg class="lang__chev" viewBox="0 0 24 24" aria-hidden="true"><path d="m6 9 6 6 6-6"/></svg>';
function renderLangSwitch() {
  const box = document.querySelector('#lang');
  if (!box) return;
  const cur = LANGS.find((l) => l.id === I18N.lang);
  box.innerHTML = `<button type="button" class="lang__btn" aria-haspopup="true" aria-expanded="false" aria-label="${t('Язык сайта')}: ${cur.name}">`
    + `<img class="lang__flag" src="${cur.flag}" alt=""><span class="lang__name">${cur.name}</span>${CHEV}</button>`
    + `<div class="lang__menu" role="menu">${LANGS.map((l) => `<button type="button" role="menuitemradio" aria-checked="${l.id === cur.id}" data-lang="${l.id}" lang="${l.html}">`
      + `<img class="lang__flag" src="${l.flag}" alt="">${l.name}</button>`).join('')}</div>`;
}

function setLang(id, quiet) {
  if (!LANGS.some((l) => l.id === id)) return;
  const changed = I18N.lang !== id;
  I18N.lang = id;
  try { localStorage.setItem(LANG_KEY, id); } catch (_) { /* приватный режим */ }
  translatePage();
  renderLangSwitch();
  if (changed && !quiet) dispatchEvent(new Event('langchange')); // страницы перерисовывают то, что собрано скриптом
}

function initLang() {
  if (document.documentElement.dataset.i18n === 'off') return; // админка — только по-русски
  let id = new URLSearchParams(location.search).get('lang');
  if (!LANGS.some((l) => l.id === id)) { try { id = localStorage.getItem(LANG_KEY); } catch (_) { id = null; } }
  setLang(LANGS.some((l) => l.id === id) ? id : 'ru', true);

  const box = document.querySelector('#lang');
  if (!box) return;
  const close = () => { box.classList.remove('is-open'); box.querySelector('.lang__btn')?.setAttribute('aria-expanded', 'false'); };
  box.addEventListener('click', (e) => {
    const pick = e.target.closest('[data-lang]');
    if (pick) { close(); setLang(pick.dataset.lang); box.querySelector('.lang__btn').focus(); return; }
    if (e.target.closest('.lang__btn')) {
      const open = box.classList.toggle('is-open');
      box.querySelector('.lang__btn').setAttribute('aria-expanded', open);
      if (open) box.querySelector('.lang__menu [aria-checked="true"]').focus();
    }
  });
  document.addEventListener('click', (e) => { if (!box.contains(e.target)) close(); });
  box.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && box.classList.contains('is-open')) { close(); box.querySelector('.lang__btn').focus(); }
    if ((e.key === 'ArrowDown' || e.key === 'ArrowUp') && box.classList.contains('is-open')) {
      e.preventDefault();
      const items = [...box.querySelectorAll('.lang__menu button')];
      const i = items.indexOf(document.activeElement);
      items[(i + (e.key === 'ArrowDown' ? 1 : items.length - 1)) % items.length].focus();
    }
  });
}

initLang(); // скрипт подключён в конце body — вёрстка уже на месте
